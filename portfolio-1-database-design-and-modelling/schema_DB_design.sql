    "TXN_ID"             NUMBER(9)	   GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 999999999999999 INCREMENT BY 4 START WITH 1 CACHE 20 NOORDER NOCYCLE,
