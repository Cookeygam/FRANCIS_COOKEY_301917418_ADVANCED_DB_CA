CREATE ROLE ROLE_SUPPORT_RO;    -- support staff: read only.
CREATE ROLE ROLE_AML_TXN_READ;  -- Compliance reading TRANSACT data for AML spotting
CREATE ROLE ROLE_DB_MAINT;      -- DBA / tuning tasks (flashback, debug, query rewrite)

